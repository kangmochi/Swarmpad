/**
 * Bundles the API entry into api/v1.js.
 *
 * Vercel does not bundle the functions in this project: it runs the entry file
 * and leaves relative imports to Node, which cannot resolve a .ts sibling. So
 * the entry is bundled here into one file with no imports, and api/v1.js is the
 * function the deployment serves. The source lives in api/_src, which Vercel
 * ignores because of the underscore.
 */

import { fileURLToPath } from "node:url";
import path from "node:path";

import { build } from "rolldown";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const banner = `// Generated by scripts/build-api.mjs from api/_src/v1.ts. Do not edit.
// Rebuild with: npm run api:build
`;

await build({
  input: path.join(root, "api/_src/v1.ts"),
  platform: "node",
  output: {
    file: path.join(root, "api/v1.js"),
    format: "esm",
    banner,
    inlineDynamicImports: true,
  },
});

console.log("api/v1.js written");
